// Generates src/generated.ts (policy, result and protocol-message types) from ../../schema/.
//   node scripts/gen-types.mjs          write the file
//   node scripts/gen-types.mjs --check  exit 1 when the file is stale (the unit tests run this)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "../../../schema");
const OUT = join(here, "../src/generated.ts");

const load = (name) => JSON.parse(readFileSync(join(schemaDir, name), "utf8"));
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (k) => (IDENT.test(k) ? k : JSON.stringify(k));
const lit = (v) => JSON.stringify(v);

function merge(parent, child) {
  const { oneOf: _o, ...base } = parent;
  return {
    ...base,
    ...child,
    properties: { ...base.properties, ...child.properties },
    required: [...new Set([...(base.required ?? []), ...(child.required ?? [])])],
    allOf: [...(base.allOf ?? []), ...(child.allOf ?? [])],
  };
}

function doc(text, pad) {
  return text ? `${pad}/** ${text.replace(/\*\//g, "*\\/")} */\n` : "";
}

function ts(s, pad = "") {
  if (s.$ref) return `Wire${s.$ref.split("/").pop()}`;
  if (s.const !== undefined) return lit(s.const);
  if (s.enum) return s.enum.map(lit).join(" | ");
  if (s.oneOf) return s.oneOf.map((b) => ts(merge(s, b), pad)).join(" | ");
  const parts = (s.allOf ?? []).map((p) => ts(p, pad));
  const types = [].concat(s.type ?? []);
  const isObj = types.includes("object") || s.properties || s.required || s.additionalProperties || s.propertyNames;
  const alts = types.filter((t) => t !== "object").map(primitive(s, pad));
  if (isObj) {
    const o = object(s, pad);
    if (o !== "{}" || parts.length === 0) alts.push(o);
  }
  if (alts.length) {
    const union = alts.join(" | ");
    parts.push(parts.length || alts.length > 1 ? `(${union})` : union);
  }
  return parts.length ? parts.join(" & ") : "unknown";
}

const primitive = (s, pad) => (t) => {
  switch (t) {
    case "string": return "string";
    case "integer": case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": return `${wrap(s.items ? ts(s.items, pad) : "unknown")}[]`;
    default: throw new Error(`unsupported schema type ${t}`);
  }
};
const wrap = (t) => (/[|&]/.test(t) ? `(${t})` : t);

function object(s, pad) {
  const props = s.properties ?? {};
  const names = [...new Set([...Object.keys(props), ...(s.required ?? [])])];
  const extra = s.additionalProperties && typeof s.additionalProperties === "object" ? ts(s.additionalProperties, pad) : null;
  if (names.length === 0) {
    if (s.propertyNames?.enum) return `{ [K in ${s.propertyNames.enum.map(lit).join(" | ")}]?: ${extra ?? "unknown"} }`;
    return extra ? `Record<string, ${extra}>` : s.additionalProperties === false ? "{}" : "Record<string, unknown>";
  }
  const inner = `${pad}  `;
  const lines = names.map((n) => {
    const optional = (s.required ?? []).includes(n) ? "" : "?";
    const p = props[n];
    return `${doc(p?.description, inner)}${inner}${key(n)}${optional}: ${p ? ts(p, inner) : "unknown"};\n`;
  });
  if (extra) lines.push(`${inner}[key: string]: ${extra} | undefined;\n`);
  return `{\n${lines.join("")}${pad}}`;
}

export function generate() {
  const protocol = load("protocol/protocol.schema.json");
  const policy = load("policy.schema.json");
  let out = [
    "// GENERATED by scripts/gen-types.mjs from schema/policy.schema.json and schema/protocol/protocol.schema.json.",
    "// Do not edit: run `npm run gen:types`. The unit tests fail when this file is stale.",
    "",
    "",
  ].join("\n");
  out += `${doc(policy.description, "")}export type Policy = ${ts(policy)};\n`;
  for (const [name, schema] of Object.entries(protocol.$defs)) {
    out += `\n${doc(schema.description, "")}export type Wire${name} = ${ts(schema)};\n`;
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUT, "utf8"); } catch { /* missing counts as stale */ }
    if (current !== next) {
      console.error("src/generated.ts is stale: run `npm run gen:types` in clients/node");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
  }
}
